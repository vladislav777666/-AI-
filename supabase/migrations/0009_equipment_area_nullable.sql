-- ============================================================
-- 0009: оборудование можно открепить от участка (ТЗ §2.1).
--
-- В 0002 equipment.area_id был NOT NULL, поэтому снятие галочки в поле
-- «Закреплённое оборудование» справочника участков ничего не меняло:
-- у оборудования просто не существовало состояния «без участка».
-- Теперь участок — необязательная привязка: единица оборудования остаётся
-- в справочнике §2.3, но может быть не закреплена ни за одним участком.
--
-- Миграция идемпотентна: повторный запуск схему не меняет.
-- ============================================================

alter table public.equipment alter column area_id drop not null;

comment on column public.equipment.area_id is
  'Участок закрепления; NULL — оборудование без участка (ТЗ §2.1/§2.3)';
