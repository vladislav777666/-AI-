-- 0007_head_analytics.sql
-- Веб-панель руководителя: данные, которых не хватало для разделов 2 и 3.
--
--   Раздел 2, п.4 «Количество и сложность закрытых нарядов»: каждому типу
--     поломки нужен весовой коэффициент сложности 1..5 (1 — мелкий ремонт,
--     5 — капитальный). Общий балл исполнителя = Σ сложность закрытых нарядов.
--
--   Раздел 3.4 «По материалам»: чтобы сравнивать материальный норматив с
--     фактическими затратами, шифру нужен норматив в числовом виде
--     (material_norm — это текстовая номенклатура из §2.5, её недостаточно).
--
-- Выполнить в Supabase → SQL Editor после 0006_user_roles.sql
-- (либо `supabase db push` из каталога проекта).

begin;

-- ============================================================
-- 1. Весовой коэффициент сложности типа поломки (Раздел 2 п.4).
-- ============================================================
alter table public.fault_codes add column if not exists complexity smallint;

update public.fault_codes
   set complexity = 3
 where complexity is null;

alter table public.fault_codes
  alter column complexity set default 3;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'fault_codes_complexity_check'
  ) then
    alter table public.fault_codes
      add constraint fault_codes_complexity_check check (complexity between 1 and 5);
  end if;
end;
$$;

-- ============================================================
-- 2. Материальный норматив в единицах списания (Раздел 3.4).
--    Плановое количество ТМЦ на один наряд; факт берём из
--    work_orders.materials_list (Σ qty).
-- ============================================================
alter table public.fault_codes add column if not exists material_norm_qty numeric(10, 2);

-- ============================================================
-- 3. Заполнение коэффициентов по действующему справочнику §2.5.
--    Идемпотентно: перезаписываем только известные коды.
-- ============================================================
update public.fault_codes as f
   set complexity = v.complexity,
       material_norm_qty = v.norm_qty
  from (values
    ('М-01', 3::smallint,  4::numeric),
    ('М-02', 3,            3),
    ('М-03', 2,            2),
    ('М-04', 5,            6),
    ('Э-01', 1,            3),
    ('Э-02', 3,            5),
    ('Э-03', 5,            4),
    ('Э-04', 2,            2),
    ('Г-01', 2,            2),
    ('Г-02', 4,            5),
    ('Г-03', 2,            2),
    ('П-01', 1,            2),
    ('П-02', 3,            3),
    ('С-01', 1,            2),
    ('С-02', 2,            3)
  ) as v(code, complexity, norm_qty)
 where f.code = v.code;

-- Права не меняются: колонки наследуют политики fault_codes
-- («fault_codes: read all» и «fault_codes: web write» из 0006).

commit;

